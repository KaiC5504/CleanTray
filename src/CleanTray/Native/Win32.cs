    static extern int SHGetKnownFolderPath([MarshalAs(UnmanagedType.LPStruct)] Guid id, uint flags, IntPtr token, out IntPtr path);

    /// <summary>The folder's path, or null for a GUID this machine doesn't know.</summary>
    public static string? KnownFolderPath(Guid id)
    {
        var hr = SHGetKnownFolderPath(id, 0, IntPtr.Zero, out var path);
        try
        {
            return hr == 0 ? Marshal.PtrToStringUni(path) : null;
        }
        finally
        {
            Marshal.FreeCoTaskMem(path);
        }
    }
